"""Draw the logo, once, in every form the site and Google need.

The mark is a letter D whose inside is cut as a keyhole: D for DSAI, the keyhole for the
vault. It is defined here as one SVG path; this script writes it out as

    static/brand/logo.svg              the tab icon in modern browsers, rounded corners
    static/brand/favicon-32.png        the tab icon for browsers that want a bitmap
    static/brand/apple-touch-icon.png  the home-screen icon on phones (they round it)
    static/brand/logo-512.png          square, for Google's consent screen and anywhere
    static/brand/logo-120.png          a logo is asked for
    templates/components/logo.html     the bare glyph, drawn in the page's own colours

Re-run after changing the shape or the colours:

    uv run --with resvg-py python tools/make_icons.py

resvg renders SVG to PNG; it is needed only here, so it is not a dependency of the site.
"""

from pathlib import Path

import resvg_py

ROOT = Path(__file__).resolve().parent.parent
BRAND = ROOT / "static" / "brand"

# The site's --primary and --on-primary at the default hue (static/css/tokens.css),
# converted from OKLCH: a file that leaves the site cannot use CSS variables.
BLUE = "#1b589e"
WHITE = "#fafcfe"

# On a 512 x 512 canvas. First the D (flat left side with rounded corners, a half circle
# on the right), then the keyhole (most of a circle, widening into a stem). With
# fill-rule="evenodd" the second shape is cut out of the first.
GLYPH = (
    "M166 116H240A140 140 0 0 1 240 396H166A30 30 0 0 1 136 366V146A30 30 0 0 1 166 116Z"
    "M222 266.4A46 46 0 1 1 266 266.4L282 328Q284 336 276 336H212Q204 336 206 328Z"
)


def svg(corner, scale=1.0):
    """The whole icon. `corner` rounds the background; `scale` enlarges the glyph a
    little for sizes where it would otherwise be a few pixels tall."""
    grow = (
        f' transform="translate(256 256) scale({scale}) translate(-256 -256)"' if scale != 1 else ""
    )
    return (
        '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512">'
        f'<rect width="512" height="512" rx="{corner}" fill="{BLUE}"/>'
        f'<path fill="{WHITE}" fill-rule="evenodd"{grow} d="{GLYPH}"/>'
        "</svg>\n"
    )


def png(name, size, **shape):
    data = bytes(resvg_py.svg_to_bytes(svg_string=svg(**shape), width=size, height=size))
    (BRAND / name).write_bytes(data)
    print(f"  static/brand/{name}  {size} x {size}")


def main():
    BRAND.mkdir(parents=True, exist_ok=True)
    (BRAND / "logo.svg").write_text(svg(corner=116), encoding="utf-8", newline="\n")
    print("  static/brand/logo.svg")
    png("favicon-32.png", 32, corner=116, scale=1.12)
    png("apple-touch-icon.png", 180, corner=0)
    png("logo-512.png", 512, corner=0)
    png("logo-120.png", 120, corner=0)

    partial = (
        "{# Generated by tools/make_icons.py. Do not edit. The glyph takes the text colour. #}\n"
        '<svg class="brand__glyph" viewBox="0 0 512 512" aria-hidden="true">'
        f'<path fill="currentColor" fill-rule="evenodd" d="{GLYPH}"/></svg>\n'
    )
    (ROOT / "templates" / "components" / "logo.html").write_text(
        partial, encoding="utf-8", newline="\n"
    )
    print("  templates/components/logo.html")


if __name__ == "__main__":
    main()
