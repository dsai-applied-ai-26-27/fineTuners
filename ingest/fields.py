"""Turn the Pydantic models in schemas.py into Markdown field tables for the docs.

`manage.py export_schemas` writes the result to docs/content-types/fields.md. Authors (and
AI agents) read that file; because it is generated from the same models the importer uses,
it is always exactly what sync_content accepts.
"""

import datetime as dt
import types
from typing import Annotated, Literal, Union, get_args, get_origin

from pydantic import AfterValidator, BaseModel, StringConstraints
from pydantic_core import PydanticUndefined

from .schemas import SCHEMAS

FILES = {
    "course": "course.yaml",
    "document": "content/lectures|labs|homework|guides/<name>.md (front matter), "
    "content/reference/cheatsheet.md",
    "deck": "content/decks/<deck>.yaml",
    "problem-set": "content/problems/<set>.yaml",
    "paper": "content/exams/<exam>/<paper>.yaml",
    "assessment": "content/exams/<exam>/assessment.yaml",
    "formulas": "content/reference/formulas.yaml",
    "glossary": "content/reference/glossary.yaml",
    "hooks": "content/memory/hooks.yaml",
    "palace": "content/memory/palaces/<palace>.yaml",
}


def _string_kind(metadata):
    for item in metadata:
        if isinstance(item, AfterValidator):
            return "Markdown"
        if isinstance(item, StringConstraints):
            if item.pattern:
                return "id"
            if item.max_length:
                return "text (one line)"
    return "text"


def _describe(annotation, metadata, nested):
    """Human name of a field's type. Nested models are collected in `nested`."""
    origin = get_origin(annotation)
    if origin is Annotated:
        inner, *extra = get_args(annotation)
        return _describe(inner, [*extra, *metadata], nested)
    if origin in (Union, types.UnionType):
        options = [arg for arg in get_args(annotation) if arg is not type(None)]
        return " or ".join(_describe(option, metadata, nested) for option in options)
    if origin is Literal:
        return " \\| ".join(
            f"`{value}`" if value != "" else '`""`' for value in get_args(annotation)
        )
    if origin is list:
        return f"list of {_describe(get_args(annotation)[0], [], nested)}"
    if isinstance(annotation, type) and issubclass(annotation, BaseModel):
        if annotation not in nested:
            nested.append(annotation)
        return f"[{annotation.__name__}](#{annotation.__name__.lower()})"
    if annotation is str:
        return _string_kind(metadata)
    return {int: "whole number", float: "number", bool: "`true` \\| `false`", dt.date: "date"}.get(
        annotation, getattr(annotation, "__name__", str(annotation))
    )


def _default(info):
    if info.is_required():
        return "**required**"
    if info.default_factory is not None:
        value = info.default_factory()
        if isinstance(value, BaseModel) or value in ([], {}):
            return ""
    value = info.default
    if value in (None, PydanticUndefined, ""):
        return ""
    return f"default `{str(value).lower() if isinstance(value, bool) else value}`"


def _table(model, nested):
    rows = ["| Field | Type | | Meaning |", "|---|---|---|---|"]
    for name, info in model.model_fields.items():
        kind = _describe(info.annotation, list(info.metadata), nested)
        meaning = (info.description or "").replace("|", "\\|")
        rows.append(f"| `{info.alias or name}` | {kind} | {_default(info)} | {meaning} |")
    return "\n".join(rows)


def render_markdown():
    out = [
        "# Field reference",
        "",
        "<!-- Generated by `manage.py export_schemas` from ingest/schemas.py. Do not edit. -->",
        "",
        "Every field of every content file. Unknown fields are rejected. Types:",
        "",
        "- **Markdown**: rendered text (maths, callouts, links, code). Write it in a block "
        "scalar (`|-`).",
        "- **text (one line)**: a short plain label, at most 200 characters.",
        "- **id**: lowercase letters, digits and single hyphens, e.g. `fisher-01`.",
        "- **date**: `YYYY-MM-DD`, unquoted.",
        "",
    ]
    described = set()
    for name, model in SCHEMAS.items():
        nested = []
        out += [f"## {name}", "", f"File: `{FILES[name]}`", ""]
        if model.__doc__:
            out += [" ".join(model.__doc__.split()), ""]
        out += [_table(model, nested), ""]
        position = 0
        while position < len(nested):
            child = nested[position]
            position += 1
            if child in described:
                continue
            described.add(child)
            out += [f"### {child.__name__}", ""]
            if child.__doc__ and child.__doc__ != BaseModel.__doc__:
                out += [" ".join(child.__doc__.split()), ""]
            out += [_table(child, nested), ""]
    return "\n".join(out).rstrip() + "\n"
